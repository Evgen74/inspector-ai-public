#!/usr/bin/env node
/**
 * Generates src/api/schema.gen.ts from the REST contract the API serves: packages/contracts/openapi/openapi.yaml
 * plus the pending AG-08 overlays in apps/api/openapi/pending (same merge rule as the API: overlays only add).
 *
 *   pnpm --filter @inspector/web gen:api          # write
 *   pnpm --filter @inspector/web gen:api --check  # exit 1 when the committed file is stale
 *
 * The same `generateApiTypes()` is used by the freshness test (src/api/schema.gen.test.ts).
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { parse } from 'yaml';

const here = path.dirname(fileURLToPath(import.meta.url));
export const WEB_ROOT = path.resolve(here, '..');
const REPO = path.resolve(WEB_ROOT, '..', '..');
export const BASE_DOC = path.join(REPO, 'packages', 'contracts', 'openapi', 'openapi.yaml');
export const PENDING_DIR = path.join(REPO, 'apps', 'api', 'openapi', 'pending');
export const OUT_FILE = path.join(WEB_ROOT, 'src', 'api', 'schema.gen.ts');

const KINDS = ['schemas', 'parameters', 'responses', 'headers', 'requestBodies'];

/** Base document + overlays (paths/components/tags the base does not have yet). */
export function mergedDocument() {
  const doc = parse(readFileSync(BASE_DOC, 'utf8'));
  const overlays = existsSync(PENDING_DIR)
    ? readdirSync(PENDING_DIR).filter((f) => f.endsWith('.yaml')).sort().map((f) => path.join(PENDING_DIR, f))
    : [];
  for (const file of overlays) {
    const o = parse(readFileSync(file, 'utf8'));
    for (const [p, item] of Object.entries(o.paths ?? {})) if (!(p in doc.paths)) doc.paths[p] = item;
    doc.components ??= {};
    for (const kind of KINDS) {
      for (const [name, def] of Object.entries(o.components?.[kind] ?? {})) {
        doc.components[kind] ??= {};
        if (!(name in doc.components[kind])) doc.components[kind][name] = def;
      }
    }
    doc.tags ??= [];
    for (const tag of o.tags ?? []) if (!doc.tags.some((t) => t.name === tag.name)) doc.tags.push(tag);
  }
  return { doc, overlays: overlays.map((f) => path.relative(REPO, f)) };
}

export async function generateApiTypes() {
  const { doc, overlays } = mergedDocument();
  const ast = await openapiTS(doc, { alphabetize: true, exportType: true });
  const header = [
    '/**',
    ' * GENERATED by apps/web/scripts/gen-api-types.mjs (openapi-typescript) — do not edit.',
    ' * Source: packages/contracts/openapi/openapi.yaml',
    ...overlays.map((o) => ` *       + ${o} (pending AG-00 adoption)`),
    ' * Regenerate: pnpm --filter @inspector/web gen:api',
    ' */',
    '',
  ].join('\n');
  return header + astToString(ast);
}

async function main() {
  const text = await generateApiTypes();
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT_FILE) ? readFileSync(OUT_FILE, 'utf8') : '';
    if (current !== text) {
      console.error('src/api/schema.gen.ts устарел: выполните pnpm --filter @inspector/web gen:api');
      process.exit(1);
    }
    console.log('src/api/schema.gen.ts актуален');
    return;
  }
  writeFileSync(OUT_FILE, text);
  console.log(`Записан ${path.relative(REPO, OUT_FILE)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
